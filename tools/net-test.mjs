// Online check: two separate browser contexts, host creates a PeerJS room, guest joins by code,
// host starts a race; both must see the shared simulation advancing. Usage: node tools/net-test.mjs [base]
import { chromium } from '/home/alexandr/projects/smash64/node_modules/playwright/index.mjs';
const BASE = process.argv[2] || 'http://127.0.0.1:8321/';
const browser = await chromium.launch({ executablePath: '/home/alexandr/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome', args: ['--no-sandbox', '--enable-unsafe-swiftshader', '--use-angle=swiftshader-webgl'] });
let fails = 0; const check = (c, n) => { console.log(c ? 'PASS' : 'FAIL', n); if (!c) fails++; };
const mk = async () => { const ctx = await browser.newContext({ viewport: { width: 900, height: 540 } }); const p = await ctx.newPage();
  p.on('pageerror', e => console.log('PAGEERROR', e.message)); return p; };
const host = await mk(), guest = await mk();
await host.goto(BASE + '?screen=online', { waitUntil: 'load' }); await host.waitForTimeout(1500);
await host.fill('input[placeholder="Your name"]', 'Hosty');
await host.click('button:has-text("CREATE ROOM")');
await host.waitForSelector('.bigcode', { timeout: 30000 });
const code = (await host.textContent('.bigcode')).trim();
console.log('room code', code); check(/^[A-Z]{4}$/.test(code), 'host created room with 4-letter code');
await guest.goto(BASE + '?room=' + code, { waitUntil: 'load' }); await guest.waitForTimeout(1500);
await guest.click(`button:has-text("JOIN ROOM ${code}")`); await guest.waitForTimeout(800);
await guest.fill('input[placeholder="Your name"]', 'Guesty');
await guest.click('button:has-text("JOIN ROOM")');
await guest.waitForSelector('.bigcode', { timeout: 30000 });
check(true, 'guest reached lobby');
await host.waitForTimeout(1500);
const hostLobby = await host.textContent('.screen');
check(hostLobby.includes('Guesty'), 'host lobby shows guest');
await host.click('button:has-text("START!")');
await host.waitForTimeout(9000);
const hs = await host.evaluate(() => window.__KART__?.state());
const gs = await guest.evaluate(() => window.__KART__?.state());
console.log('host state', JSON.stringify(hs?.me), 'phase', hs?.phase, 'time', hs?.time);
console.log('guest state', JSON.stringify(gs?.me), 'phase', gs?.phase, 'time', gs?.time, 'karts', JSON.stringify(gs?.karts?.map(k => k.speed)));
check(hs?.race && hs.phase === 'racing', 'host simulating race');
check(gs?.race && gs.time > 1, 'guest receiving synced race state');
check(gs.karts.some(k => k.speed > 5), 'guest sees karts moving');
await guest.keyboard.down('ArrowUp'); await guest.waitForTimeout(3500); await guest.keyboard.up('ArrowUp');
const gs2 = await guest.evaluate(() => window.__KART__?.state());
console.log('guest after driving', JSON.stringify(gs2?.me));
check(gs2.me.speed > 3 || gs2.me.progress > gs.me.progress, 'guest input drives its kart on host sim');
await host.screenshot({ path: 'comparisons/round6/ours/net_host.png' }).catch(() => {});
await guest.screenshot({ path: 'comparisons/round6/ours/net_guest.png' }).catch(() => {});
await browser.close();
console.log(fails ? `\n${fails} FAILURES` : '\nONLINE OK');
process.exit(fails ? 1 : 0);
